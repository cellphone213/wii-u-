"""Generate the Ren'Py files that make a game show Arabic.

Nothing in the game is edited. The patch is a handful of new files:

* ``game/zz_vnarabizer.rpy`` – loads the dialogue table, turns on
  right-to-left text, swaps fonts for an Arabic one and selects the language.
  Written so it runs on both Python 2 (Ren'Py 6/7) and Python 3 (Ren'Py 8).
* ``game/vnarabizer/say.json`` – dialogue and menu translations, looked up by
  the exact original script text through ``config.say_menu_text_filter``.
* ``game/tl/<lang>/vnarabizer_strings.rpy`` – interface text and character
  names, using Ren'Py's own ``translate <lang> strings`` mechanism.
* ``game/vnarabizer/*.ttf`` – the Arabic font.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from .quote import quote

PATCH_RPY = "zz_vnarabizer.rpy"
DATA_DIR = "vnarabizer"


@dataclass
class PatchOptions:
    language: str = "arabic"
    font_regular: str = "vnarabizer/VNArabic-Regular.ttf"
    font_bold: str = "vnarabizer/VNArabic-Bold.ttf"
    replace_fonts: bool = True
    keep_fonts: tuple[str, ...] = ()  # font files the user wants left alone (icon fonts etc.)
    align_right: bool = True
    force_language: bool = True
    use_harfbuzz: bool = True


def say_json(say: dict[str, str]) -> bytes:
    return json.dumps(say, ensure_ascii=False, sort_keys=True, indent=0).encode("utf-8")


def strings_rpy(strings: dict[str, tuple[str, str]], language: str, align_right: bool = True) -> str:
    """``strings`` maps original -> (translation, "file:line" comment)."""
    lines: list[str] = ["# Generated by VN Arabizer. Interface text and character names.", ""]
    if align_right:
        # Per-language style changes: Ren'Py applies these after it rebuilds
        # styles on a language switch, so they are not lost.
        for st in ("say_dialogue", "nvl_dialogue"):
            lines += [f"translate {language} style {st}:", "    text_align 1.0", ""]
    lines += [f"translate {language} strings:", ""]
    if not strings:
        lines.append('    old "\\u200b__vnarabizer_placeholder__"')
        lines.append('    new "\\u200b__vnarabizer_placeholder__"')
    for old in sorted(strings):
        new, where = strings[old]
        if where:
            lines.append(f"    # {where}")
        lines.append(f"    old {quote(old)}")
        lines.append(f"    new {quote(new)}")
        lines.append("")
    return "\n".join(lines) + "\n"


def main_rpy(opt: PatchOptions) -> str:
    keep = json.dumps(list(opt.keep_fonts))
    return f'''# Generated by VN Arabizer.
# To remove the Arabic translation use the app's "Remove" button, or delete
# this file, its .rpyc, the "vnarabizer" folder and tl/{opt.language}/vnarabizer_strings.*

init 999 python:
    import json as _vna_json

    _VNA_LANG = "{opt.language}"
    _VNA_REGULAR = "{opt.font_regular}"
    _VNA_BOLD = "{opt.font_bold}"
    _VNA_KEEP = set({keep})

    def _vna_read(name):
        try:
            f = renpy.open_file(name)
        except Exception:
            f = renpy.file(name)
        try:
            data = f.read()
        finally:
            f.close()
        if not isinstance(data, type(u"")):
            data = data.decode("utf-8")
        return _vna_json.loads(data)

    try:
        _vna_say = _vna_read("vnarabizer/say.json")
    except Exception:
        _vna_say = {{}}

    # Dialogue and menu choices: looked up by the exact original script text,
    # before the game's own filter (if any) runs.
    _vna_prev_filter = config.say_menu_text_filter

    def _vna_filter(s):
        t = _vna_say.get(s, s)
        if _vna_prev_filter is not None:
            t = _vna_prev_filter(t)
        return t

    config.say_menu_text_filter = _vna_filter

    # Right-to-left text with Arabic letter joining.
    config.rtl = True
'''+ (f'''
    # Use HarfBuzz shaping where the engine has it (Ren'Py 8.2+).
    try:
        if renpy.version_tuple >= (8, 2):
            style.default.shaper = "harfbuzz"
    except Exception:
        pass
''' if opt.use_harfbuzz else "") + (f'''
    # Every font the game asks for is drawn with the Arabic font instead,
    # except image fonts and fonts the user chose to keep (icons etc.).
    _vna_font_decisions = {{}}

    def _vna_keep_font(fn):
        if fn in _vna_font_decisions:
            return _vna_font_decisions[fn]
        keep = False
        try:
            low = fn.lower()
            if fn in _VNA_KEEP or low.startswith("vnarabizer/"):
                keep = True
            elif any(w in low for w in ("awesome", "icon", "emoji", "symbol", "material", "dingbat")):
                keep = True
            else:
                for k in renpy.text.font.image_fonts:
                    if k[0] == fn:
                        keep = True
                        break
        except Exception:
            keep = True
        _vna_font_decisions[fn] = keep
        return keep

    class _VNAFontMap(dict):
        def get(self, key, default=None):
            if dict.__contains__(self, key):
                return dict.__getitem__(self, key)
            try:
                fn, bold, italics = key
            except Exception:
                return default
            if not isinstance(fn, (type(u""), type(""))) or _vna_keep_font(fn):
                return default
            if bold:
                return (_VNA_BOLD, False, italics)
            return (_VNA_REGULAR, False, italics)

    config.font_replacement_map = _VNAFontMap(config.font_replacement_map)
''' if opt.replace_fonts else "") + (f'''
    # Start the game in Arabic.
    config.default_language = _VNA_LANG
    try:
        config.language = _VNA_LANG
    except Exception:
        pass
''' if opt.force_language else "")
