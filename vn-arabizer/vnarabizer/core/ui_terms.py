_LOWER = {k.lower(): v for k, v in UI_TERMS.items()}


def lookup(text: str) -> str | None:
    s = text.strip()
    hit = UI_TERMS.get(s) or _LOWER.get(s.lower())
    if hit is None:
        return None
    # Keep surrounding whitespace exactly as in the original.
    lead = text[: len(text) - len(text.lstrip())]
    trail = text[len(text.rstrip()) :]
    return lead + hit + trail
