"""A tiny RPG Maker MV/MZ game layout for tests."""

from __future__ import annotations

import json
from pathlib import Path


def cmd(code, params, indent=0):
    return {"code": code, "indent": indent, "parameters": params}


def make_game(root: Path, mz: bool = False) -> Path:
    web = root if mz else root / "www"
    (web / "data").mkdir(parents=True)
    (web / "js" / "plugins").mkdir(parents=True)
    (web / "fonts").mkdir(parents=True)
    core = "rmmz_core.js" if mz else "rpg_core.js"
    (web / "js" / core).write_text(f'Utils.RPGMAKER_NAME = "{"MZ" if mz else "MV"}";\nUtils.RPGMAKER_VERSION = "{"1.8.0" if mz else "1.6.2"}";\n')
    (web / "js" / "plugins.js").write_text(
        "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n"
        '{"name":"Community_Basic","status":true,"description":"","parameters":{"screenWidth":"816","screenHeight":"624"}}\n];\n'
    )
    data = web / "data"
    header = ["Actor1", 0, 0, 2] + (["ハロルド"] if mz else [])
    map_list = [
        cmd(101, header),
        cmd(401, ["\\C[2]こんにちは、\\N[1]さん！"]),
        cmd(401, ["今日は\\V[3]ゴールドを持っているね。"]),
        cmd(102, [["はい", "いいえ"], 1, 0, 2, 0]),
        cmd(402, [0, "はい"]),
        cmd(101, ["", 0, 0, 2], 1),
        cmd(401, ["よかった。"], 1),
        cmd(0, [], 1),
        cmd(402, [1, "いいえ"]),
        cmd(0, [], 1),
        cmd(404, []),
        cmd(355, ["$gameVariables.setValue(1, 'こんにちは')"]),
        cmd(356, ["ShowPicture hero.png"]),
        cmd(108, ["メモ: これはコメント"]),
        cmd(231, [1, "Actor1_face", 0, 0, 0, 0, 100, 100, 255, 0]),
        cmd(0, []),
    ]
    (data / "Map001.json").write_text(json.dumps({
        "displayName": "はじまりの村", "note": "<tag>",
        "events": [None, {"id": 1, "name": "EV001", "note": "", "pages": [{"list": map_list}]}],
    }, ensure_ascii=False))
    (data / "MapInfos.json").write_text(json.dumps([None, {"id": 1, "name": "MAP001"}]))
    (data / "CommonEvents.json").write_text(json.dumps([None, {"id": 1, "name": "CE", "list": [
        cmd(101, ["", 0, 0, 2]), cmd(401, ["Hello there."]), cmd(401, ["How are you today?"]), cmd(0, [])]}],
        ensure_ascii=False))
    (data / "Actors.json").write_text(json.dumps([None, {"id": 1, "name": "ハロルド", "nickname": "", "profile": "勇敢な若者。",
                                                         "faceName": "Actor1", "battlerName": "Actor1_1", "note": "<plugin:data>"}], ensure_ascii=False))
    (data / "Items.json").write_text(json.dumps([None, {"id": 1, "name": "ポーション", "description": "HPを500回復する。", "iconIndex": 176, "note": ""}], ensure_ascii=False))
    (data / "States.json").write_text(json.dumps([None, {"id": 1, "name": "毒", "message1": "は毒にかかった！", "message2": "", "message3": "", "message4": "の毒が消えた！"}], ensure_ascii=False))
    system = {
        "gameTitle": "テストゲーム", "currencyUnit": "G", "locale": "ja_JP",
        "elements": ["", "物理", "炎"], "skillTypes": ["", "魔法"], "weaponTypes": ["", "剣"],
        "armorTypes": ["", "盾"], "equipTypes": ["", "武器"],
        "terms": {"basic": ["レベル", "Lv"], "commands": ["戦う", None, "逃げる"], "params": ["最大HP"],
                  "messages": {"actionFailure": "%1には効かなかった！", "file": "ファイル"}},
        "title1Name": "Castle",
    }
    if mz:
        system["advanced"] = {"uiAreaWidth": 816, "fontSize": 26, "screenWidth": 816}
    (data / "System.json").write_text(json.dumps(system, ensure_ascii=False))
    (data / "Tilesets.json").write_text("[null]")
    return root
